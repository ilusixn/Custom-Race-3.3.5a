"""Per race (Esteria ids 80-91) and sex: (skin colours, hair colours, facial-hair styles) of the pack races, from the merged client DBCs.
Writes the C++ table PackCounts.inl; mk_banks.py imports counts() for the option records."""
import os, sys, importlib.util
spec = importlib.util.spec_from_file_location('mydbc', 'C:/CoA-Build/allraces12/dbc.py'); m_ = importlib.util.module_from_spec(spec); spec.loader.exec_module(m_); D = m_.D
O = 'C:/CoA-Build/allraces12/out/client/'
NAMES = ['Sureki', 'Dreadlord', 'Titan', 'Wretched', 'Fungarian', 'Sporeling', 'Stormforged', 'Moarg', 'Nerubian', 'Lich', 'Mogu', 'LostOne']
DBC = [86, 89, 91, 92, 93, 111, 114, 119, 120, 122, 123, 125]
SK = [18, 10, 9, 64, 11, 11, 13, 8, 8, 7, 12, 9]                  # skin colours offered (PackSkins)
cs = D(O + 'CharSections.dbc'); cf = D(O + 'CharacterFacialHairStyles.dbc')


def hair_rows(did, sex):
    """section 3 rows, variation 0, one per colour"""
    rows = {}
    for x in cs.rows:
        if x[1] == did and x[2] == sex and x[3] == 3 and x[8] == 0:
            rows.setdefault(x[9], x)
    return [rows[k] for k in sorted(rows)]


def facial_rows(did, sex):
    return sorted([x for x in cf.rows if x[0] == did and x[1] == sex], key=lambda x: x[2])


def counts(i, sex):
    if NAMES[i] == 'Mogu':
        return SK[i], 1, max(1, len(facial_rows(DBC[i], sex)))        # only the Features slider works on the Mogu
    if NAMES[i] == 'Fungarian':
        return SK[i], 8, 1               # glowing-eye colours, beard styles (cap and back growth are the extra controls below)
    return SK[i], max(1, len(hair_rows(DBC[i], sex))), max(1, len(facial_rows(DBC[i], sex)))


def extra(i, sex):
    return (1, 1)       # Fungarian: caps (none + 5), back growths (none + 3)


if __name__ == '__main__':
    lines = ['// generated by allraces12/pack_counts.py: {skin colours, hair colours, facial-hair styles} per pack race (80-91) and gender',
             'inline constexpr unsigned PackCounts[12][2][3] = {']
    for i, n in enumerate(NAMES):
        a, b = counts(i, 0), counts(i, 1)
        lines.append('    {{%d, %d, %d}, {%d, %d, %d}},   // %s' % (a + b + (n,)))
        print(n, a, b)
    lines.append('};')
    lines += ['inline constexpr unsigned PackExtra[12][2][2] = {'] + ['    {{%d, %d}, {%d, %d}},' % (extra(i, 0) + extra(i, 1)) for i in range(12)] + ['};']
    open('C:/CoA-Build/coa64/CoA/Source/Modules/Esteria/PackCounts.inl', 'w').write('\n'.join(lines) + '\n')
